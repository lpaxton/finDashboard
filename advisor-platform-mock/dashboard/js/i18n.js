/*
 * Language (AX-12). One dictionary, no build step, no dependency — the same constraints as the
 * rest of this dashboard.
 *
 * The key is the English string itself. With around five hundred of them, inventing an
 * identifier for each would mean touching every call site twice and inventing a name for
 * "Nothing across the firm needs you today." The cost of this choice is that two English
 * strings which happen to match but should differ in French collide; where that happens the key
 * carries a context suffix after a double bar ("Report||noun"), which t() strips before
 * falling back.
 *
 * A missing translation renders the English and warns once, rather than rendering a key or an
 * empty string. A half-translated screen is legible; "advisor.today.empty" is not. The warnings
 * are the to-do list for whoever reviews the French.
 *
 * NOT TRANSLATED, deliberately: anything that stands for a record in a system — household and
 * people's names, alert and compliance titles as they arrive from the custodian or CRM. Those
 * are data, and translating them is a data decision rather than a language one. Server copy in
 * the platform's own voice IS translated, server-side, from the same stored preference.
 */

export const LANGS = [['en', 'English'], ['fr', 'Français']];
const LOCALE = { en: 'en-US', fr: 'fr-FR' };

let lang = 'en';
export const getLang = () => lang;
export const locale = () => LOCALE[lang] || 'en-US';

/* Set on <html> so the browser hyphenates, speaks and spell-checks in the right language, and
   so CSS can key off it. Changing it re-renders the current view rather than reloading: the
   advisor keeps their place. */
const listeners = new Set();
export const onLangChange = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };
export function setLang(l) {
  if (!LANGS.some(([k]) => k === l) || l === lang) return false;
  lang = l;
  document.documentElement.lang = l;
  listeners.forEach(fn => fn(l));
  return true;
}

const missing = new Set();
const BAR = '||';

/* Data wearing a UI slot. head() and load() translate their titles, which is how five hundred
   panel headings got localised with two edits — but some of those titles are a person's name or
   a household's, and a name is not a missing translation. raw() says so explicitly rather than
   letting t() guess. */
const RAW = Symbol('raw');
export const raw = (s) => ({ [RAW]: true, toString: () => String(s ?? '') });
const isRaw = (v) => !!(v && typeof v === 'object' && v[RAW]);

/* t('Due {n} days', { n: 3 }). Placeholders are substituted after lookup, so the French can put
   them in a different order, which it often must. */
export function t(key, vars) {
  if (isRaw(key)) return String(key);
  const dict = DICT[lang];
  let out = dict ? dict[key] : null;
  if (out == null) {
    if (dict && !missing.has(key)) { missing.add(key); console.warn('[i18n] no ' + lang + ' for:', key); }
    out = key.includes(BAR) ? key.slice(0, key.indexOf(BAR)) : key;
  }
  if (vars) for (const k of Object.keys(vars)) out = out.split('{' + k + '}').join(vars[k]);
  return out;
}

/* What has not been translated yet, for the review pass. Read it from the console:
   `import('./js/i18n.js').then(m => console.table(m.untranslated()))`. */
export const untranslated = () => [...missing];

